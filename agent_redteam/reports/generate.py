"""Report generation: Markdown human report, CSV findings export."""

from __future__ import annotations

import csv
import time
from pathlib import Path

from agent_redteam.core.schemas import ComparisonReport, RunSummary


def generate_markdown_report(
    summary: RunSummary,
    results: list,
    out_path: str | Path,
    comparison: ComparisonReport | None = None,
) -> Path:
    m = summary.metrics
    lines: list[str] = []
    lines.append("# Agent Red-Team Evaluation Report")
    lines.append("")
    lines.append(f"- **Run ID:** `{summary.run_id}`")
    lines.append(f"- **Date:** {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(summary.created_at))}")
    lines.append(f"- **Suite:** `{summary.suite}`")
    lines.append(f"- **Target:** `{summary.target}`")
    lines.append("")
    lines.append("## Summary Metrics")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    lines.append(f"| Total cases | {m.total_cases} |")
    lines.append(f"| Executed | {m.executed} |")
    lines.append(f"| Violations | {m.violations} |")
    lines.append(f"| Errors | {m.errors} |")
    lines.append(f"| Attack success rate | {m.attack_success_rate:.2%} |")
    lines.append(f"| Violation rate | {m.violation_rate:.2%} |")
    lines.append(f"| Pass rate | {m.pass_rate:.2%} |")
    if m.avg_latency_ms is not None:
        lines.append(f"| Avg latency | {m.avg_latency_ms:.1f} ms |")
    lines.append("")
    lines.append("## Category Breakdown")
    lines.append("")
    lines.append("| Category | Total | Violations | Errors | Violation rate |")
    lines.append("|---|---|---|---|---|")
    for cat, s in sorted(m.by_category.items()):
        lines.append(
            f"| {cat} | {int(s['total'])} | {int(s['violations'])} | {int(s['errors'])} "
            f"| {s['violation_rate']:.2%} |"
        )
    lines.append("")
    lines.append("## Findings")
    if not summary.findings:
        lines.append("")
        lines.append("_No policy violations found._")
    for f in summary.findings:
        lines.append("")
        lines.append(f"### [{f.severity.value.upper()}] {f.title} (`{f.test_id}`)")
        lines.append(f"- **Category:** {f.category}")
        lines.append(f"- **Reproduction:** {f.reproduction}")
        lines.append(f"- **Remediation:** {f.remediation}")
        for ev in f.evidence:
            lines.append(f"- **Evidence ({ev.kind}):** {ev.detail}")
    if comparison is not None:
        lines.append("")
        lines.append("## Baseline Comparison")
        lines.append("")
        lines.append(f"- Baseline: `{comparison.baseline_run_id}` -> Current: `{comparison.current_run_id}`")
        lines.append(
            "- Metric deltas: "
            + ", ".join(f"{k}: {v:+.2%}" for k, v in comparison.metric_deltas.items())
        )
        lines.append(f"- Regressions: **{len(comparison.regressions)}**")
        for r in comparison.regressions:
            lines.append(f"  - `{r.test_id}` ({r.category}): {r.detail}")
        lines.append(f"- Improvements: **{len(comparison.improvements)}**")
        for r in comparison.improvements:
            lines.append(f"  - `{r.test_id}` ({r.category}): {r.detail}")
        if comparison.unchanged_violations:
            lines.append(f"- Still violating: {len(comparison.unchanged_violations)}")
            for r in comparison.unchanged_violations:
                lines.append(f"  - `{r.test_id}` ({r.category}): {r.detail}")
    lines.append("")
    lines.append("---")
    lines.append(
        "_Generated by the Agent Red-Teaming & Evaluation Framework. "
        "Evidence and artifacts are stored locally under runs/._"
    )
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def generate_findings_csv(summary: RunSummary, out_path: str | Path) -> Path:
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(
            ["finding_id", "test_id", "category", "severity", "title", "reproduction", "remediation"]
        )
        for f in summary.findings:
            w.writerow(
                [f.id, f.test_id, f.category, f.severity.value, f.title, f.reproduction, f.remediation]
            )
    return out
